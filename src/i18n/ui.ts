export type UIKey = keyof (typeof ui)['ja'];

export function useTranslations(lang: Lang) {
  return function t(key: UIKey, vars?: Record<string, string | number>): string {
    let s: string = ui[lang][key] ?? ui[defaultLang][key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/** Build an internal URL for a given language, e.g. href('ja', 'products/') → '/ja/products/' */
export function href(lang: Lang, path = ''): string {
  const clean = path.replace(/^\/+/, '');
  return `/${lang}/${clean}`;
}

export const htmlLang: Record<Lang, string> = { ja: 'ja', en: 'en', ko: 'ko' };

export const locales: Record<Lang, string> = { ja: 'ja-JP', en: 'en-US', ko: 'ko-KR' };

export function formatPrice(price: number, lang: Lang): string {
  return new Intl.NumberFormat(locales[lang], { style: 'currency', currency: 'JPY', currencyDisplay: 'narrowSymbol' }).format(price);
}

export function langPaths() {
  return langs.map((lang) => ({ params: { lang } }));
}
